from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

from pydantic import BaseModel, Field


class LogEntry(BaseModel):
    at: str
    action: str
    actor: str
    doc_ids: list[str] = Field(default_factory=list)
    note: str


class ScaffoldEntry(BaseModel):
    content: str
    cli_owned: bool


class InitResult(BaseModel):
    root: Path
    created: list[str] = Field(default_factory=list)
    overwritten: list[str] = Field(default_factory=list)
    skipped: list[str] = Field(default_factory=list)


def format_log_entry(entry: LogEntry) -> str:
    ids = ",".join(entry.doc_ids) if entry.doc_ids else "-"
    return f"- {entry.at} | {entry.action} | {entry.actor} | {ids} | {entry.note}"


def _utc_now() -> str:
    value = datetime.now(timezone.utc).replace(microsecond=0)
    return value.isoformat().replace("+00:00", "Z")


def _index(title: str, description: str, listing: str = "") -> str:
    content = (
        f"---\ntype: index\ndescription: {description}\n---\n"
        f"# {title}\n\n"
        "<!-- Generated by kb — do not edit; run `kb index` to regenerate. -->\n"
    )
    return content if not listing else f"{content}\n{listing}\n"


