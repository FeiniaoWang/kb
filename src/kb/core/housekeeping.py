def _log_content(timestamp: str) -> str:
    entry = format_log_entry(
        LogEntry(
            at=timestamp,
            action="initialized",
            actor="kb-cli",
            doc_ids=[],
            note="KB scaffolded by kb init",
        )
    )
    return (
        "---\ntype: log\n---\n"
        "<!-- KB history — append-only; written by `kb log`. Format: - <UTC ISO> | <action> | <actor> | <ids or -> | <note> -->\n"
        f"# Knowledge Base Log\n\n{entry}\n"
    )


