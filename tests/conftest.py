def expected_index(title: str, description: str, listing: str = "") -> str:
    content = (
        f"---\ntype: index\ndescription: {description}\n---\n"
        f"# {title}\n\n"
        "<!-- Generated by kb — do not edit; run `kb index` to regenerate. -->\n"
    )
    return content if not listing else f"{content}\n{listing}\n"


